"""Embed every file in sandbox/agent_tools/ into sandbox/setup.sh.

`mda` uploads only setup.sh to the bake sandbox (as /tmp/mda-setup.sh), so the CLIs must be
inlined there. Run after adding or editing a file in agent_tools/:
`uv run python scripts/embed_cli.py`.
"""
from __future__ import annotations

import re
from pathlib import Path

SANDBOX = Path(__file__).parent.parent / "sandbox"
TOOLS = SANDBOX / "agent_tools"
BLOCK = re.compile(
    r"^# >>> embedded agent_tools.*?\n.*?^# <<< embedded agent_tools\n", re.S | re.M
)


def tool_files() -> list[Path]:
    # Skip dotfiles and __pycache__ so stray local artifacts aren't baked in.
    return sorted(p for p in TOOLS.iterdir() if p.is_file() and not p.name.startswith("."))


def render(files: list[Path]) -> str:
    parts = ["# >>> embedded agent_tools (generated by scripts/embed_cli.py)\n"]
    for f in files:
        marker = "EOF_" + re.sub(r"\W", "_", f.name).upper()
        body = f.read_text()
        assert not body.endswith("\n\n") and f"\n{marker}\n" not in "\n" + body, f.name
        if not body.endswith("\n"):
            body += "\n"
        dest = f"/agent_tools/{f.name}"
        parts.append(f"cat > {dest} <<'{marker}'\n{body}{marker}\nchmod a+rx {dest}\n")
    parts.append("# <<< embedded agent_tools\n")
    return "".join(parts)


def main() -> None:
    files = tool_files()
    assert files, f"no files in {TOOLS}"
    setup = SANDBOX / "setup.sh"
    text, n = BLOCK.subn(lambda _: render(files), setup.read_text())
    assert n == 1, "setup.sh must contain one '# >>> embedded agent_tools' block"
    setup.write_text(text)


if __name__ == "__main__":
    main()
